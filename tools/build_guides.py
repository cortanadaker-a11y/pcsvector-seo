def parse_bah(slug):
    h = read("bah/%s/index.html" % slug)
    rows = {}
    t = re.search(r"<table>.*?</table>", h, flags=re.S).group(0)
    for tr in re.findall(r"<tr><td>([^<]+)</td><td>[^<]*</td><td>\$([\d,]+)</td><td>\$([\d,]+)</td></tr>", t):
        rows[tr[0]] = (int(tr[1].replace(",", "")), int(tr[2].replace(",", "")))
    m = re.search(r"DTMO lists this housing area as <strong>([^<]+)</strong> \(code ([A-Z]{2}\d{3})\)", h)
    r = re.search(r"runs about <strong>(\$[\d,]+.\$[\d,]+)/month</strong>, and utilities for that home \(([^)]*)\) run about <strong>(\$[\d,]+.\$[\d,]+)/month", h)
    return dict(rows=rows, mha_name=m.group(1), mha_code=m.group(2), rent=r.group(1) if r else None, util=r.group(3) if r else None)

