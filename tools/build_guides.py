def fix_th(h):
    """Accessibility: header cells inside <thead> get scope="col" (idempotent)."""
    def thead(m):
        return re.sub(r"<th(?![^>]*\bscope=)(\s[^>]*)?>", lambda t: "<th scope=\"col\"%s>" % (t.group(1) or ""), m.group(0))
    return re.sub(r"<thead>.*?</thead>", thead, h, flags=re.S)

def touch_modified(h):
    return re.sub(r'("dateModified": ")[0-9-]+(")', r"\g<1>%s\2" % TODAY, h)

def build_bah():
    all_data = {s: parse_bah(s) for s in NAMES}
    for slug in NAMES:
        p = "bah/%s/index.html" % slug
        h = read(p)
        h = strip(h, "guide"); h = strip(h, "faq"); h = strip(h, "related")
        if slug in GD.GUIDES:
            h = put(h, "guide", guide_block(slug, all_data[slug], all_data), "<h2>ZIP codes in the ")
            if GD.GUIDES[slug].get("faq"):
                h = put(h, "faq", faq_html(slug, all_data[slug]), '<section class="agents">')
                h = add_faq_jsonld(h, [(q, fmt_faq(a, all_data[slug], GD.GUIDES[slug]["short"])) for q, a in GD.GUIDES[slug]["faq"]])
        h = put(h, "related", related_block(slug), "<h2>Other posts</h2>")
        h = prune_faq_jsonld(h, p)
        if slug in GD.GUIDES:
            h = touch_modified(h)   # unguided pages only gain a related-links block: leave dateModified alone
        write(p, h)

