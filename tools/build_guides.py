def strip(h, name):
    return re.sub(r"\n?<!--pcsv:%s-->.*?<!--/pcsv:%s-->\n?" % (name, name), "\n", h, flags=re.S)

def put(h, name, block, before):
    h = strip(h, name)
    assert before in h, "anchor %r missing" % before[:40]
    i = h.index(before)
    return h[:i] + "<!--pcsv:%s-->\n%s\n<!--/pcsv:%s-->\n" % (name, block, name) + h[i:]

def src_links(keys):
    out = []
    for k in keys:
        t, u = GD.SOURCES[k]
        out.append('<a href="%s" rel="noopener">%s</a>' % (E(u, quote=True), E(t)))
    return out

def cite(keys):
    if not keys: return ""
    return ' <span class="note">(%s)</span>' % "; ".join(src_links(keys))

def li(items):
    return "".join("<li>%s%s</li>" % (E(t), cite(k)) for t, k in items)

